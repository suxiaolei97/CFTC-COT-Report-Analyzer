def set_lang(lang: str) -> None:
    global _current_lang
    if lang in _TRANSLATIONS:
        _current_lang = lang


def t(key: str, **kwargs) -> str:
    text = _TRANSLATIONS.get(_current_lang, {}).get(key, _TRANSLATIONS["en"].get(key, key))
    if kwargs:
        return text.format(**kwargs)
    return text


